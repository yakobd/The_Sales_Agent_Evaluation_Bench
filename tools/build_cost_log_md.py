"""Render cost_log.md from cost_log.jsonl (the raw per-call log written by llm_client.py)."""
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    rows = [json.loads(l) for l in (ROOT / "cost_log.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    by = defaultdict(lambda: {"calls": 0, "usd": 0.0, "pt": 0, "ct": 0})
    for r in rows:
        k = (r["bucket"], r["model"])
        by[k]["calls"] += 1
        by[k]["usd"] += r["cost_usd"]
        by[k]["pt"] += r.get("prompt_tokens") or 0
        by[k]["ct"] += r.get("completion_tokens") or 0
    total = sum(r["cost_usd"] for r in rows)
    first, last = rows[0]["ts"][:10], rows[-1]["ts"][:10]
    lines = [
        "# Cost Log",
        "",
        f"Generated by `tools/build_cost_log_md.py` from [cost_log.jsonl](cost_log.jsonl). That file holds one line per OpenRouter call, "
        "written by [llm_client.py](llm_client.py), which also enforces the $5 budget cap and caches responses.",
        "",
        f"**Total: ${total:.4f} over {len(rows)} calls ({first} to {last}).** "
        "Training, generation and the ablation ran on a free Google Colab T4, at $0.",
        "",
        "| Bucket | Model | Calls | Prompt tok | Completion tok | USD |",
        "|---|---|---|---|---|---|",
    ]
    for (b, m), v in sorted(by.items(), key=lambda kv: -kv[1]["usd"]):
        lines.append(f"| {b} | {m} | {v['calls']} | {v['pt']:,} | {v['ct']:,} | {v['usd']:.4f} |")
    lines += [
        "",
        "Bucket meanings:",
        "",
        "- `training`: SFT data. This covers the Llama-3.3-70B teacher, the 3-teacher pilot (Llama, Mistral and Gemma) and the Mistral-written prospect messages for train-side reply tasks.",
        "- `dataset_authoring`: held-out prospect messages (Mistral), candidate replies (Gemma) and the judge filter (DeepSeek).",
        "- `reserve`: client smoke tests.",
        "",
        "The v0.1 cost log reported $0.00 for every line and is superseded. Earlier spend from v0.1 was not logged per call, so it is not included here.",
        "",
    ]
    (ROOT / "cost_log.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"cost_log.md: ${total:.4f}, {len(rows)} calls")


if __name__ == "__main__":
    main()
